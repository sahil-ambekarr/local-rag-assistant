import fs from 'node:fs';
import path from 'node:path';
import type { RetrievalMetrics } from '../src/evalMetrics.js';
import { pct, RESULTS_DIR, ROOT } from './common.js';

interface Env {
  date: string;
  node: string;
  platform: string;
  cpu: string;
  memoryGb: number;
  note: string;
}

interface RetrievalResult extends Env {
  embedModel: string;
  chunkSize: number;
  chunkOverlap: number;
  k: number;
  documents: number;
  chunks: number;
  ingestMs: number;
  queryMedianMs: number;
  chunkLevel: RetrievalMetrics;
  sourceLevel: RetrievalMetrics;
  perQuestion: { id: string; question: string; expectedSource: string; chunkRank: number | null; sourceRank: number | null; top: { source: string }[] }[];
}

interface FaithfulnessResult extends Env {
  chatModel: string;
  embedModel: string;
  topK: number;
  questions: number;
  factRate: number;
  citationRate: number;
  bothRate: number;
  generationMedianMs: number;
  generationMaxMs: number;
  perQuestion: { id: string; question: string; answer: string; cited: number[]; factOk: boolean; citationOk: boolean; generationMs: number; error?: string }[];
}

function load<T>(name: string): T | undefined {
  const file = path.join(RESULTS_DIR, name);
  return fs.existsSync(file) ? (JSON.parse(fs.readFileSync(file, 'utf8')) as T) : undefined;
}

const envLine = (e: Env) =>
  `Run on ${e.date} with Node ${e.node} on ${e.platform}, ${e.cpu}, ${e.memoryGb} GB RAM. ${e.note}`;

/** Regenerates docs/eval-results.md from the JSON files in docs/eval/. */
export function writeReport(): string {
  const r = load<RetrievalResult>('retrieval.json');
  const f = load<FaithfulnessResult>('faithfulness.json');
  const out: string[] = ['# Eval results', '', 'Generated by `eval/report.ts` from the raw JSON in `docs/eval/`. Do not edit by hand; rerun the eval instead.', ''];

  if (r) {
    out.push(
      '## Retrieval',
      '',
      envLine(r),
      '',
      `Embedding model \`${r.embedModel}\`, chunk size ${r.chunkSize} characters with ${r.chunkOverlap} overlap, ` +
        `${r.documents} documents in ${r.chunks} chunks, top ${r.k} retrieved per question. ` +
        `Indexing the corpus took ${(r.ingestMs / 1000).toFixed(1)} s; median query time (embed the question plus brute-force search) was ${r.queryMedianMs} ms.`,
      '',
      '| Level | Questions | Hit@1 | Hit@3 | Hit@5 | MRR |',
      '| --- | --- | --- | --- | --- | --- |',
      ...(
        [
          ['Chunk (right file and the chunk holding the evidence)', r.chunkLevel],
          ['Source (right file anywhere in the list)', r.sourceLevel],
        ] as const
      ).map(([name, m]) => `| ${name} | ${m.questions} | ${pct(m.hitRateAt1)} | ${pct(m.hitRateAt3)} | ${pct(m.hitRateAt5)} | ${m.mrr.toFixed(3)} |`),
      '',
      '### Per question',
      '',
      '| Id | Question | Expected source | Chunk rank | Top-1 source |',
      '| --- | --- | --- | --- | --- |',
      ...r.perQuestion.map((q) => `| ${q.id} | ${q.question} | ${q.expectedSource} | ${q.chunkRank ?? 'miss'} | ${q.top[0]?.source ?? '-'} |`),
      '',
    );
  }

  if (f) {
    out.push(
      '## Answer spot check',
      '',
      envLine(f),
      '',
      `Chat model \`${f.chatModel}\` through Ollama, embeddings \`${f.embedModel}\`, top ${f.topK} passages in the prompt, ${f.questions} questions asked one at a time.`,
      '',
      'Method: an answer passes the **fact check** when it contains every expected keyword group (for example "24" for the annual leave question). ' +
        'It passes the **citation check** when at least one [n] marker in the answer points at a passage from the expected file. ' +
        'This is a keyword proxy. It does not verify each claim in the answer against the passages, so a wrong extra sentence would not be caught.',
      '',
      '| Fact check | Citation check | Both | Median generation time | Slowest |',
      '| --- | --- | --- | --- | --- |',
      `| ${pct(f.factRate)} | ${pct(f.citationRate)} | ${pct(f.bothRate)} | ${(f.generationMedianMs / 1000).toFixed(1)} s | ${(f.generationMaxMs / 1000).toFixed(1)} s |`,
      '',
      '### Answers',
      '',
      ...f.perQuestion.flatMap((q) => [
        `**${q.id}. ${q.question}** fact ${q.factOk ? 'pass' : 'fail'}, citation ${q.citationOk ? 'pass' : 'fail'}, ${(q.generationMs / 1000).toFixed(1)} s`,
        '',
        `> ${(q.error ? `Error: ${q.error}` : q.answer).replace(/\s*\n+\s*/g, ' ').trim()}`,
        '',
      ]),
    );
  }

  const file = path.join(ROOT, 'docs', 'eval-results.md');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out.join('\n'));
  return file;
}
